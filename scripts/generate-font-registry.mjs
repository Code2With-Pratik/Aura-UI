import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const root = process.cwd();
const fontsRoot = path.join(root, "public", "fonts");
const output = path.join(root, "lib", "fonts", "registry.ts");
const downloadsRoot = path.join(root, "public", "downloads");
const collectionLicense = path.join(fontsRoot, "LICENSE");

const weightMap = {
  thin: 100, extralight: 200, semilight: 350, light: 300, regular: 400,
  book: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800,
  ultra: 900, black: 900,
};

const titleCase = (value) => value.replace(/([a-z])([A-Z])/g, "$1 $2").replace(/[-_]+/g, " ").trim();
const slugify = (value) => value.toLowerCase().replace(/_complete$/i, "").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const full = path.join(dir, entry.name);
  return entry.isDirectory() ? walk(full) : [full];
});
const parseFile = (familyDir, file) => {
  const base = path.basename(file, ".woff2");
  const parts = base.split("-");
  const tokens = parts.slice(1).map((part) => part.toLowerCase());
  const isVariable = tokens.includes("variable");
  const isItalic = tokens.includes("italic");
  const weightToken = tokens.find((token) => weightMap[token] !== undefined);
  const weight = weightToken ? weightMap[weightToken] : 400;
  return {
    file: path.relative(root, file).replaceAll(path.sep, "/"),
    url: "/" + path.relative(path.join(root, "public"), file).replaceAll(path.sep, "/"),
    weight,
    style: isItalic ? "italic" : "normal",
    variable: isVariable,
    weightRange: isVariable ? "100 900" : undefined,
    label: parts.slice(1).join(" ") || "Regular",
    familyDir,
  };
};

const dirs = fs.readdirSync(fontsRoot, { withFileTypes: true }).filter((entry) => entry.isDirectory());
const families = dirs.map((entry) => {
  const familyDir = entry.name;
  const familyName = familyDir.replace(/_Complete$/i, "");
  const files = walk(path.join(fontsRoot, familyDir)).filter((file) => file.toLowerCase().endsWith(".woff2"));
  const faces = files.map((file) => parseFile(familyDir, file)).sort((a, b) => a.weight - b.weight || a.style.localeCompare(b.style));
  const styles = [...new Set(faces.map((face) => face.style))];
  const weights = [...new Set(faces.filter((face) => !face.variable).map((face) => face.weight))].sort((a, b) => a - b);
  const variable = faces.find((face) => face.variable);
  const category = /script|britney|caveat|dancing|kalam|kola|telma|hoover/i.test(familyName)
    ? "Handwritten" : /slab|melodrama|trench/i.test(familyName) ? "Display" : /rajdhani|technor|nippo|styro|satoshi|poppins|quicksand/i.test(familyName) ? "Sans Serif" : "Experimental";
  return {
    id: slugify(familyName), name: titleCase(familyName), slug: slugify(familyName), category,
    directory: familyDir, cssUrl: `/fonts/${slugify(familyName)}.css`,
    license: { status: "review", redistributable: false, file: fs.existsSync(path.join(fontsRoot, familyDir, "LICENSE")) ? `public/fonts/${familyDir}/LICENSE` : fs.existsSync(collectionLicense) ? "public/fonts/LICENSE (collection license; upstream font license still required)" : "No license file found" },
    weights: weights.length ? weights : [400], styles, variable: variable ? { file: variable.url, axes: { wght: "100 900" } } : null,
    files: faces.map(({ familyDir: _familyDir, ...face }) => face),
  };
}).sort((a, b) => a.name.localeCompare(b.name));

fs.mkdirSync(path.dirname(output), { recursive: true });
const header = `/* Auto-generated by scripts/generate-font-registry.mjs. Do not edit manually. */\n\n`;
fs.writeFileSync(output, `${header}export type FontFace = ${JSON.stringify({ file: "", url: "", weight: 400, style: "normal", variable: false, label: "" }, null, 2).replace(/"([^"\n]+)":/g, "$1:").replace(/: ""/g, ": string").replace(/: 400/g, ": number").replace(/: false/g, ": boolean")}\n`);
fs.writeFileSync(output, `${header}export type FontFile = { file: string; url: string; weight: number; style: "normal" | "italic"; variable: boolean; weightRange?: string; label: string };\nexport type FontFamily = { id: string; name: string; slug: string; category: string; directory: string; cssUrl: string; license: { status: "review" | "approved"; redistributable: boolean; file: string; }; weights: number[]; styles: string[]; variable: { file: string; axes: { wght: string } } | null; files: FontFile[] };\nexport const fontRegistry: FontFamily[] = ${JSON.stringify(families, null, 2)} as FontFamily[];\nexport const fontBySlug = (slug: string) => fontRegistry.find((font) => font.slug === slug);\n`);

const cssFor = (family) => family.files.map((face) => `@font-face { font-family: "${family.name}"; src: url("${face.url}") format("woff2"); font-weight: ${face.variable ? face.weightRange : face.weight}; font-style: ${face.style}; font-display: swap; }`).join("\n");
for (const family of families) {
  if (!family.license.redistributable) continue;
  fs.mkdirSync(downloadsRoot, { recursive: true });
  const dir = path.join(downloadsRoot, family.slug);
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(path.join(dir, "README.md"), `# ${family.name}\n\nInstall via https://aura-ui-os.vercel.app${family.cssUrl}.\n\nLicense status: ${family.license.status}.\n`);
  const files = family.files.map((face) => path.join(root, face.file));
  try {
    if (process.platform === "win32") execFileSync("tar", ["-a", "-c", "-f", path.join(downloadsRoot, `${family.slug}.zip`), "-C", dir, "README.md", ...files.map((file) => path.relative(dir, file))], { stdio: "ignore" });
  } catch { /* ZIPs remain unavailable until an approved license is supplied. */ }
}
console.log(`Generated ${families.length} font families and ${families.reduce((count, family) => count + family.files.length, 0)} WOFF2 files.`);
